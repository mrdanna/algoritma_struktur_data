import numpy as np

# Array dari list
nilai = np.array([80, 75, 90, 85, 70])

# Array nol
nol = np.zeros(5)

# Array berisi 1
satu = np.ones(5)

# Array berisi 0..4
angka = np.arange(5)

# Array berisi 0..9 dengan 5 elemen berjarak sama
lin = np.linspace(0, 9, 5)

print(nilai)
print(nol)
print(satu)
print(angka)
print(lin)
